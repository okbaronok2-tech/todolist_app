// US-07 할일 등록 (카테고리 미지정과 지정) (PS-02, 시드 7건)
await setup();
await clearSession();
const reqs = [];
page.on('request', (r) => { if (r.url().includes(':3000/api/todos')) reqs.push(r.method() + ' ' + r.url()); });
await login('seojun@example.com', 'seojun1234');
const noToday = reqs.filter((u) => !u.includes('today=2026-11-03'));
ok('US-12 보강: 목록 요청(GET /api/todos)에 today=2026-11-03 포함, 누락 요청 목록', noToday.length === 0, noToday.join(' ; ') || reqs.join(' ; '));
await page.getByRole('button', { name: '등록' }).click();
await page.waitForURL('**/todos/new'); await page.locator('#title').waitFor();
ok('US-07-1 [등록] → /todos/new', page.url().endsWith('/todos/new') && (await page.locator('h1.page-title').textContent()) === '할일 등록', await page.locator('h1.page-title').textContent());
await fillTodoForm({ title: '고객 미팅 준비', startDate: '2026-11-05', endDate: '2026-11-05' });
await shot('US-07-2-form');
await page.getByRole('button', { name: '저장' }).click();
await page.waitForURL('**/todos'); await waitList();
ok('US-07-2 저장 → /todos 8건', (await titles()).length === 8);
await page.getByRole('button', { name: '등록' }).click(); await page.waitForURL('**/todos/new');
await fillTodoForm({ title: '견적서 작성', startDate: '2026-11-03', endDate: '2026-11-04', category: '업무' });
await page.getByRole('button', { name: '저장' }).click();
await page.waitForURL('**/todos'); await waitList();
ok('US-07-3 저장 → 9건', (await titles()).length === 9);
const a = await rowInfo('고객 미팅 준비');
ok('US-07 고객 미팅 준비: 11-05~11-05, 기본, 시작 전, 미완료', a.period === '11-05~11-05' && a.category === '기본' && a.status === '시작 전' && !a.checked, JSON.stringify(a));
const b = await rowInfo('견적서 작성');
ok('US-07 견적서 작성: 11-03~11-04, 업무, 진행중', b.period === '11-03~11-04' && b.category === '업무' && b.status === '진행중', JSON.stringify(b));
const order = await titles();
const exp = ['헬스장 등록', '주간 보고서 제출', '거래처 견적 회신', '분기 계획 작성', '은행 서류 제출', '견적서 작성', '팀 회의 자료 준비', '고객 미팅 준비', '가족 여행 준비'];
ok('US-07 목록 순서 6,1,2,5,4,견적서,3,고객,7', JSON.stringify(order) === JSON.stringify(exp), order.join(' > '));
await shot('US-07-3-list-9');
