// US-18 모바일 375px 핵심 흐름 (PS-01, 시드 상태)
await setup({ width: 375, height: 740 });
await clearSession();
await page.goto(BASE + '/login');
await page.getByRole('link', { name: '가입 화면' }).click(); await page.waitForURL('**/signup'); await sleep(200);
const fieldW = await page.locator('.field').first().evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length);
ok('US-18-1 /signup 단일 열', fieldW === 1, `grid columns=${fieldW}`);
await shot('US-18-1-signup-mobile');
await page.goBack(); await page.waitForURL('**/login');
await login('haneul@example.com', 'haneul1234');
const menuBtn = page.getByRole('button', { name: '메뉴' });
ok('US-18-2 로그인 → /todos, 상단 간이 메뉴 [메뉴] 버튼 표시', await menuBtn.isVisible());
await shot('US-18-2-todos-mobile');
const openMenu = async (name) => { await menuBtn.click(); await page.getByRole('link', { name }).click(); };
await page.getByRole('button', { name: '등록' }).click(); await page.waitForURL('**/todos/new');
await fillTodoForm({ title: '중간고사 정리', startDate: '2026-11-05', endDate: '2026-11-07' });
await shot('US-18-3-form-mobile');
await page.getByRole('button', { name: '저장' }).click(); await page.waitForURL('**/todos'); await waitList();
ok('US-18-3 등록 → 2건', (await titles()).length === 2);
const [res] = await Promise.all([page.waitForResponse((r) => r.url().includes('/completed')), rowOf('알고리즘 과제').locator('input[type=checkbox]').click()]);
await sleep(300);
ok('US-18-4 할일 8 완료 체크 → 완료', res.status() === 200 && (await rowInfo('알고리즘 과제')).status === '완료');
await selectFilter({ status: '완료' });
ok('US-18-5 상태 완료 → 할일 8만', JSON.stringify(await titles()) === JSON.stringify(['알고리즘 과제']));
await selectFilter({ status: '미선택' });
ok('US-18-5 상태 미선택 → 2건', (await titles()).length === 2);
await rowOf('중간고사 정리').getByRole('button', { name: '편집' }).click(); await page.waitForURL('**/todos/*/edit'); await page.locator('#endDate').waitFor(); await sleep(300);
await fillTodoForm({ endDate: '2026-11-08' });
await page.getByRole('button', { name: '저장' }).click(); await page.waitForURL('**/todos'); await waitList();
ok('US-18-6 종료일 11-08 수정 → 11-05~11-08', (await rowInfo('중간고사 정리')).period === '11-05~11-08');
await rowOf('중간고사 정리').getByRole('button', { name: '삭제' }).click();
await shot('US-18-7-delete-dialog-mobile');
await page.getByRole('dialog').getByRole('button', { name: '확인' }).click(); await sleep(400);
ok('US-18-7 삭제 → 1건', (await titles()).length === 1);
await openMenu('카테고리 관리'); await page.waitForURL('**/categories'); await page.locator('.category-list').waitFor();
await page.locator('#newCategory').fill('시험'); await page.getByRole('button', { name: '추가' }).click(); await sleep(400);
ok('US-18-8 카테고리 시험 추가 → 3개', (await page.locator('.category-row:not(.category-row--head)').count()) === 3);
await shot('US-18-8-categories-mobile');
await openMenu('캘린더'); await page.waitForURL('**/calendar'); await page.locator('.cal--month').waitFor(); await sleep(300);
const dots = await page.locator('.cal__dots[aria-label="할일 1건"]').count();
const bars = await page.locator('.cal__bar').count();
ok('US-18-9 월 뷰: 할일 8이 11-02~11-06 칸에 표시 (점 축약 5칸 또는 막대)', dots === 5 || bars >= 1, `dots=${dots} bars=${bars}`);
await shot('US-18-9-calendar-mobile');
await menuBtn.click(); await page.getByRole('button', { name: '로그아웃' }).click(); await page.waitForURL('**/login');
ok('US-18-10 로그아웃 → /login', page.url().endsWith('/login'));
